-- EMERGENCY ONLY: restores known-insecure baseline access. Review before use.
BEGIN; SET LOCAL lock_timeout='5s';
DROP TRIGGER IF EXISTS phase1_guard_store_owner_update ON public.stores;
DROP FUNCTION IF EXISTS public.phase1_guard_store_owner_update();
DROP POLICY IF EXISTS "stores_owner_economy_update" ON public."stores";
DROP POLICY IF EXISTS "app_users_member_read" ON public."app_users";
DROP POLICY IF EXISTS "app_users_admin_insert" ON public."app_users";
DROP POLICY IF EXISTS "app_users_admin_update" ON public."app_users";
DROP POLICY IF EXISTS "app_users_admin_delete" ON public."app_users";
DROP POLICY IF EXISTS "staff_users_member_read" ON public."staff_users";
DROP POLICY IF EXISTS "staff_users_admin_insert" ON public."staff_users";
DROP POLICY IF EXISTS "staff_users_admin_update" ON public."staff_users";
DROP POLICY IF EXISTS "staff_users_admin_delete" ON public."staff_users";
DROP POLICY IF EXISTS "app_users_read_temp" ON public."app_users";
CREATE POLICY "app_users_read_temp" ON public."app_users" AS PERMISSIVE FOR SELECT TO "public" USING (true);
DROP POLICY IF EXISTS "app_users_write_store_access" ON public."app_users";
CREATE POLICY "app_users_write_store_access" ON public."app_users" AS PERMISSIVE FOR ALL TO "authenticated" USING (has_store_access(store_id)) WITH CHECK (has_store_access(store_id));
DROP POLICY IF EXISTS "authenticated_staff_crud" ON public."staff_users";
CREATE POLICY "authenticated_staff_crud" ON public."staff_users" AS PERMISSIVE FOR ALL TO "authenticated" USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "Allow authenticated users to insert stores" ON public."stores";
CREATE POLICY "Allow authenticated users to insert stores" ON public."stores" AS PERMISSIVE FOR INSERT TO "authenticated" WITH CHECK (true);
DROP POLICY IF EXISTS "Allow authenticated users to update stores" ON public."stores";
CREATE POLICY "Allow authenticated users to update stores" ON public."stores" AS PERMISSIVE FOR UPDATE TO "authenticated" USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "Allow public read stores" ON public."stores";
CREATE POLICY "Allow public read stores" ON public."stores" AS PERMISSIVE FOR SELECT TO "anon","authenticated" USING (true);
DROP POLICY IF EXISTS "stores_select_by_access" ON public."stores";
CREATE POLICY "stores_select_by_access" ON public."stores" AS PERMISSIVE FOR SELECT TO "authenticated" USING (user_has_store_access(id));
DROP POLICY IF EXISTS "stores_write_super_only" ON public."stores";
CREATE POLICY "stores_write_super_only" ON public."stores" AS PERMISSIVE FOR ALL TO "authenticated" USING (is_super_admin()) WITH CHECK (is_super_admin());
REVOKE SELECT ON public.stores,public.app_users,public.staff_users FROM PUBLIC,anon,authenticated;
DO $$ DECLARE t text; cols text; BEGIN FOREACH t IN ARRAY ARRAY['stores','app_users','staff_users'] LOOP SELECT string_agg(quote_ident(column_name),',') INTO cols FROM information_schema.columns WHERE table_schema='public' AND table_name=t; EXECUTE format('REVOKE SELECT (%s) ON public.%I FROM PUBLIC,anon,authenticated',cols,t); END LOOP; END $$;
GRANT SELECT ON public."app_users" TO "anon";
GRANT SELECT ON public."app_users" TO "authenticated";
GRANT SELECT ON public."staff_users" TO "anon";
GRANT SELECT ON public."staff_users" TO "authenticated";
GRANT SELECT ON public."stores" TO "anon";
GRANT SELECT ON public."stores" TO "authenticated";
COMMIT;
