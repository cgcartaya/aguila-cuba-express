export function localizeProcedure(entry: CatalogEntry, locale: WfLocale) {
  const { configuration } = entry;
  const translate = (text: string) => locale === "en" ? english[text] ?? text : text;
  const isNotary = entry.service === "notarizacion";
  return {
    ...configuration,
    title: isNotary ? "Notary Public" : translate(configuration.title),
    description: isNotary ? (locale === "en"
      ? "Ask WF Cargo to coordinate the signers and any required witnesses."
      : "Coordina con WF Cargo la presencia de los firmantes y testigos.") : translate(configuration.description),
    fees: configuration.fees.map(fee => ({ ...fee, label: translate(fee.label), unit: translate(fee.unit) })),
    variants: configuration.variants.map(variant => ({
      ...variant,
      title: translate(variant.title),
      requirements: variant.requirements.map(requirement => ({ ...requirement, label: translate(requirement.label) })),
    })),
  };
}
