export const ENGLISH_PATTERNS: Array<[RegExp, (...matches: string[]) => string]> = [
  [/^Quedan (\d+)$/, (_all, count) => `${count} left`],
  [/^Cantidad: (\d+)$/, (_all, count) => `Quantity: ${count}`],
  [/^(\d+) personas$/, (_all, count) => `${count} guests`],
  [/^Ver pedido \((\d+)\)$/, (_all, count) => `View order (${count})`],
  [/^(\d+) platos$/, (_all, count) => `${count} dishes`],
  [/^(\d+) bebidas$/, (_all, count) => `${count} drinks`],
  [/^(\d+) producto$/, (_all, count) => `${count} product`],
  [/^(\d+) productos$/, (_all, count) => `${count} products`],
  [/^(\d+) opción$/, (_all, count) => `${count} option`],
  [/^(\d+) opciones$/, (_all, count) => `${count} options`],
  [/^(\d+) mesa$/, (_all, count) => `${count} table`],
  [/^(\d+) mesas$/, (_all, count) => `${count} tables`],
  [/^Hasta (\d+)$/, (_all, count) => `Up to ${count}`],
  [/^(.+) activo ahora$/, (_all, names) => `${names} active now`],
  [/^Agregar (.+)$/, (_all, name) => `Add ${name}`],
  [/^Quitar uno de (.+)$/, (_all, name) => `Remove one ${name}`],
  [/^Agregar uno de (.+)$/, (_all, name) => `Add one ${name}`],
  [/^Ver foto de (.+)$/, (_all, name) => `View photo of ${name}`],
  [/^Ir al banner (\d+)$/, (_all, number) => `Go to banner ${number}`],
];

export function translateDeParisText(value: string) {
  const normalized = value.replace(/\s+/g, " ").trim();
  if (!normalized) return value;
  const exact = ENGLISH_UI[normalized];
  if (exact) return exact;
  for (const [pattern, replacement] of ENGLISH_PATTERNS) {
    const match = normalized.match(pattern);
    if (match) return replacement(...match);
  }
  return value;
}
